(function() {
    const STORAGE_KEY = "psf_lang_v2";
    let currentLang = localStorage.getItem(STORAGE_KEY) || "en";
    const listeners = [];

    function format(str, vars) {
        if (!vars) return str;
        return str.replace(/\{(\w+)\}/g, (_, k) => vars[k] !== undefined ? vars[k] : '{' + k + '}');
    }

    function t(key, vars) {
        const dict = I18N[currentLang] || I18N.en;
        const s = dict[key];
        if (s === undefined) return key;
        return vars ? format(s, vars) : s;
    }

    function applyLang(lang) {
        if (!I18N[lang]) lang = "en";
        currentLang = lang;
        localStorage.setItem(STORAGE_KEY, lang);
        document.documentElement.lang = lang;
        const dict = I18N[lang];

        // Text content
        document.querySelectorAll("[data-i18n]").forEach(el => {
            const key = el.getAttribute("data-i18n");
            if (dict[key] !== undefined) {
                el.textContent = dict[key];
            }
        });
        // Placeholders
        document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
            const key = el.getAttribute("data-i18n-placeholder");
            if (dict[key] !== undefined) {
                el.setAttribute("placeholder", dict[key]);
            }
        });
        // Title attribute
        document.querySelectorAll("[data-i18n-title]").forEach(el => {
            const key = el.getAttribute("data-i18n-title");
            if (dict[key] !== undefined) {
                el.setAttribute("title", dict[key]);
            }
        });

        // Browser tab title follows the page's main heading in the active language.
        const h = document.querySelector(".page-header h1[data-i18n], h1[data-i18n]");
        if (h && dict[h.getAttribute("data-i18n")] !== undefined) {
            const heading = dict[h.getAttribute("data-i18n")];
            const suffix = "Player Scouting & Fitness";
            document.title = heading === suffix ? suffix : `${heading} — ${suffix}`;
        }

        const btn = document.getElementById("langToggle");
        if (btn) btn.textContent = lang === "ru" ? "EN" : "RU";

        // Notify listeners (e.g. re-render dynamic chart labels / tables)
        listeners.forEach(fn => {
            try { fn(lang); } catch (e) { console.error(e); }
        });
    }

    function onChange(fn) {
        listeners.push(fn);
    }

    document.addEventListener("DOMContentLoaded", () => {
        applyLang(currentLang);
        const btn = document.getElementById("langToggle");
        if (btn) {
            btn.addEventListener("click", () => {
                applyLang(currentLang === "ru" ? "en" : "ru");
            });
        }
    });

    window.PSF_I18N = {
        applyLang,
        getLang: () => currentLang,
        t,
        onChange,
    };
})();
